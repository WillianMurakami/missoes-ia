(function initCasesCuradoria() {
  const cases = window.CASES_IA_CURADORIA || [];
  if (!Array.isArray(cases) || !cases.length || typeof missions === "undefined") return;

  const casesMission = missions.find((mission) => mission.id === "cases-ia-reais");
  if (!casesMission) return;

  casesMission.title = "Cases de IA";
  casesMission.short = "Veja exemplos reais de IA aplicada em negócios.";
  casesMission.description =
    "Uma curadoria de cases reais para ampliar repertório e inspirar novas leituras sobre o uso de IA no trabalho.";
  casesMission.cases = cases;

  const priorityOrder = ["Destaque", "Apoio", "Expansão"];
  const priorityLabel = {
    "Destaque": "Cases em destaque",
    "Apoio": "Outras referências úteis",
    "Expansão": "IA além do óbvio",
  };
  const priorityHelp = {
    "Destaque": "Exemplos mais próximos de problemas corporativos recorrentes.",
    "Apoio": "Cases que ampliam repertório sem exigir leitura técnica profunda.",
    "Expansão": "Aplicações menos óbvias para mostrar a variedade de caminhos possíveis.",
  };

  window.CASES_IA_FILTERS = window.CASES_IA_FILTERS || {
    area: "Todos",
    capability: "Todos",
    level: "Todos",
  };

  function escapeHtml(value) {
    return String(value || "")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#039;");
  }

  function domainFromUrl(url) {
    try {
      return new URL(url).hostname.replace(/^www\./, "");
    } catch (_error) {
      return "fonte externa";
    }
  }

  function uniqueOptions(key) {
    return [...new Set(cases.map((item) => item[key]).filter(Boolean))].sort((a, b) =>
      String(a).localeCompare(String(b), "pt-BR")
    );
  }

  function optionHtml(key) {
    const current = window.CASES_IA_FILTERS[key];
    return ["Todos", ...uniqueOptions(key)]
      .map((value) => `<option value="${escapeHtml(value)}" ${value === current ? "selected" : ""}>${escapeHtml(value)}</option>`)
      .join("");
  }

  function filteredCases() {
    const filters = window.CASES_IA_FILTERS;
    return cases.filter((item) => {
      return (
        (filters.area === "Todos" || item.area === filters.area) &&
        (filters.capability === "Todos" || item.capability === filters.capability) &&
        (filters.level === "Todos" || item.level === filters.level)
      );
    });
  }

  function buildMedia(item) {
    const fallback = `
      <div class="case-curadoria-fallback" aria-hidden="true">
        <span>${escapeHtml(item.company)}</span>
        <strong>${escapeHtml(item.area)}</strong>
      </div>
    `;
    if (!item.image) return fallback;
    return `
      <img src="${escapeHtml(item.image)}" alt="${escapeHtml(item.alt || item.title)}" loading="lazy" decoding="async">
      ${fallback}
    `;
  }

  function caseCard(item, index) {
    const sourceDomain = domainFromUrl(item.url);
    return `
      <article class="case-curadoria-card case-priority-${escapeHtml(String(item.priority || "").toLowerCase())}">
        <figure class="case-curadoria-media ${item.image ? "has-image" : "is-fallback"}">
          ${buildMedia(item)}
          <figcaption>${escapeHtml(sourceDomain)}</figcaption>
        </figure>
        <div class="case-curadoria-body">
          <div class="case-curadoria-meta">
            <span>Case ${index + 1} de ${cases.length}</span>
            <span>${escapeHtml(item.priority)}</span>
          </div>
          <p class="case-curadoria-company">${escapeHtml(item.company)}</p>
          <h3>${escapeHtml(item.title)}</h3>
          <p class="case-curadoria-summary">${escapeHtml(item.summary)}</p>
          <div class="case-curadoria-badges" aria-label="Classificação do case">
            <span>${escapeHtml(item.area)}</span>
            <span>${escapeHtml(item.level)}</span>
            <span>${escapeHtml(item.segment)}</span>
          </div>
          <div class="case-curadoria-insights">
            <section>
              <strong>Capacidade demonstrada</strong>
              <p>${escapeHtml(item.capability)}</p>
            </section>
            <section>
              <strong>Por que vale observar</strong>
              <p>${escapeHtml(item.value)}</p>
            </section>
            <section>
              <strong>Como usar na reflexão</strong>
              <p>${escapeHtml(item.usage)}</p>
            </section>
          </div>
          <a class="case-curadoria-link" href="${escapeHtml(item.url)}" target="_blank" rel="noreferrer">Acessar matéria original</a>
        </div>
      </article>
    `;
  }

  function prioritySection(priority, list) {
    const ordered = list.filter((item) => item.priority === priority);
    if (!ordered.length) return "";
    return `
      <section class="case-curadoria-section">
        <header class="case-curadoria-section-header">
          <div>
            <span>${escapeHtml(priority)}</span>
            <h3>${escapeHtml(priorityLabel[priority] || priority)}</h3>
            <p>${escapeHtml(priorityHelp[priority] || "")}</p>
          </div>
          <strong>${ordered.length} ${ordered.length === 1 ? "case" : "cases"}</strong>
        </header>
        <div class="case-curadoria-list">
          ${ordered.map((item) => caseCard(item, cases.findIndex((caseItem) => caseItem.id === item.id))).join("")}
        </div>
      </section>
    `;
  }

  function renderCasesCuradoriaMission(mission) {
    const panel = document.querySelector("#readingPanel");
    content = document.querySelector("#readingContent");
    if (!panel || !content) return;

    const list = filteredCases();
    panel.classList.remove("hidden");
    content.scrollTop = 0;
    content.className = "reading-content case-curadoria-content";
    content.innerHTML = `
      <article class="case-curadoria-page">
        <header class="case-curadoria-hero">
          <span>Cases reais</span>
          <h2>06. ${escapeHtml(mission.title)}</h2>
          <p>${escapeHtml(mission.description)}</p>
        </header>
        <section class="case-curadoria-filters" aria-label="Filtros de cases">
          <label>
            <span>Área</span>
            <select data-case-filter="area">${optionHtml("area")}</select>
          </label>
          <label>
            <span>Capacidade</span>
            <select data-case-filter="capability">${optionHtml("capability")}</select>
          </label>
          <label>
            <span>Nível</span>
            <select data-case-filter="level">${optionHtml("level")}</select>
          </label>
        </section>
        <div class="case-curadoria-counter">Exibindo ${list.length} de ${cases.length} cases</div>
        ${list.length ? priorityOrder.map((priority) => prioritySection(priority, list)).join("") : `<div class="empty-state">Nenhum case encontrado com esses filtros.</div>`}
      </article>
    `;

    content.querySelectorAll("[data-case-filter]").forEach((select) => {
      select.addEventListener("change", (event) => {
        window.CASES_IA_FILTERS[event.currentTarget.dataset.caseFilter] = event.currentTarget.value;
        renderCasesCuradoriaMission(mission);
      });
    });

    content.querySelectorAll(".case-curadoria-media img").forEach((image) => {
      image.addEventListener("error", () => {
        image.closest(".case-curadoria-media")?.classList.add("image-failed");
      });
    });

    if (typeof setReadingButtonState === "function") {
      setReadingButtonState(isMissionCompleted(mission.id) ? "complete" : "ready");
    }
  }

  const previousRenderReadingPanel = renderReadingPanel;
  renderReadingPanel = function renderReadingPanelWithCasesCuradoria(mission) {
    if (mission?.id === "cases-ia-reais") return renderCasesCuradoriaMission(mission);
    return previousRenderReadingPanel(mission);
  };

  if (state?.selectedMissionId === "cases-ia-reais") {
    renderDetail("cases-ia-reais");
  }
})();
